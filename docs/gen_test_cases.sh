#!/bin/sh
# #71: regenerate docs/TEST_CASES.md from the test sources (every test method whose name is a claim).
set -eu
R="$(cd "$(dirname "$0")/.." && pwd)"; OUT="$R/docs/TEST_CASES.md"
{
echo "# Test cases"; echo
echo "Generated by docs/gen_test_cases.sh from the test sources on $(date +%Y-%m-%d). Names are claims. A test that needs the models or a mock device skips itself when they are absent (see Install). Desktop-client and Android-client tests live in the build copies and are saved as patches (integrations/patches), listed at the end."
for M in liveness-api liveness-core devices desktop-ui bench interop eval; do
  D="$R/$M/src/test/java"; [ -d "$D" ] || continue
  N=$(grep -rhE "^\s*(public )?void [a-zA-Z_0-9]+\(" "$D" | wc -l | tr -d ' ')
  echo; echo "## $M ($N test methods)"; echo
  grep -rEn "^\s*(public )?void (test_|[a-z][A-Za-z0-9_]*)\(" "$D" --include=*.java | sed -E "s|^$D/||; s|\.java:[0-9]+:\s*(public )?void |: |; s|\(.*||" | sed 's|^|- |'
done
echo; echo "## Android engine library (instrumented, run on the emulator)"; echo
grep -rEn "public void test_" "$R/integrations/engine-android/engine/src/androidTest" | sed -E "s|.*/([A-Za-z]+)\.java:[0-9]+:\s*public void |- \1: |; s|\(.*||"
echo; echo "## Client patches (tests inside the patch files)"; echo
for P in "$R"/integrations/patches/0001*.patch "$R"/integrations/patches/0005*.patch "$R"/integrations/patches/0006*.patch "$R"/integrations/patches/0007*.patch; do
  echo "- $(basename "$P"): $(grep -E '^\+.*(public void test_|void test_|test\(.test_|testWidgets\(.test_| test .test_)' "$P" | wc -l | tr -d ' ') named tests"
done
} > "$OUT"
