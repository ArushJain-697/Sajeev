// #14 (WS1) | Prints the server-side property snippet for docs/CONFIG.md (Bible §7). Java 11 only.
package io.sajeev.policy;

import java.util.Properties;

/** Prints every liveness key with its default, in properties format, for the MOSIP admin's global parameters. */
public final class ConfigSnippet {

    private ConfigSnippet() {
    }

    /**
     * @param args unused
     * @throws Exception if the default config is invalid (it must not be)
     */
    public static void main(String[] args) throws Exception {
        Config c = Config.load(new Properties());
        System.out.println("# Generated by io.sajeev.policy.ConfigSnippet (#14). Defaults only; no value here is measured.");
        for (java.util.Map.Entry<String, String> e : c.all().entrySet()) {
            System.out.println(Config.PREFIX + e.getKey() + "=" + e.getValue());
        }
    }
}
