#!/bin/sh
# #64: regenerate docs/PERFORMANCE.md. The Mac table is measured now; the emulator table is read from docs/perf/emulator_stages.md,
# which comes from the instrumented test StageTimingsOnEmulatorTest (adb logcat -s STAGES). Needs the models (SAJEEV_MODELS).
set -eu
HERE="$(cd "$(dirname "$0")" && pwd)"; ROOT="$(cd "$HERE/.." && pwd)"; TOOLS="$ROOT/../tools-local"
if [ -d "$TOOLS/maven" ]; then
  export JAVA_HOME="${JAVA_HOME:-$(ls -d "$TOOLS"/jdk17/*/Contents/Home | head -1)}"
  export PATH="$(ls -d "$TOOLS"/maven/apache-maven-*/bin | head -1):$JAVA_HOME/bin:$PATH"
  : "${SAJEEV_MODELS:=$TOOLS/models}"
fi
[ -f "$HERE/target/cp.txt" ] || (cd "$ROOT" && mvn -q -o -Dmaven.repo.local="$TOOLS/m2" -pl bench -am -DskipTests package >&2)
MAC="$(java -cp "$HERE/target/classes:$(cat "$HERE/target/cp.txt")" io.sajeev.bench.StageTimingsMain "$SAJEEV_MODELS" "$ROOT/testdata/fixtures-faces/one_face.jpg" 20 2>/dev/null | grep '^|')"
CPU="$(sysctl -n machdep.cpu.brand_string 2>/dev/null || uname -m)"
{
cat <<EOF
# Performance (generated by bench/perf.sh on $(date +%Y-%m-%d))

Median milliseconds per stage for ONE processed frame, CPU execution provider, one 640x480-class face photo, 20 runs after 3 warm-ups. The texture-CNN and moire numbers have the decode and detector time of their own internal calls subtracted, so they are estimates (about +/- 10 ms). Stages run once per processed frame; the moire voter looks at 3 frames per decision.

## Mac ($CPU, JDK 17)

| Stage | ms |
|---|---|
$MAC

## Android emulator (Android 13 arm64 on the same Mac; not a phone)

| Stage | ms |
|---|---|
$(cat "$ROOT/docs/perf/emulator_stages.md")

## Acceleration (decision D35: an accelerator is used only if its scores stay within a tolerance measured on DEV recordings)

| Platform | Provider | Speed vs CPU | Output difference vs CPU | Status |
|---|---|---|---|---|
| Mac | CoreML | not timed | 7e-3 max (our CPU parity limit is 1e-4) | disabled |
| Android emulator | NNAPI | 31.5 ms vs 11.6 ms (slower; the emulator's NNAPI is a CPU reference driver) | 3.6e-7 | disabled by default; a real phone has not been measured |

## What these numbers do and do not say

- No real phone and no Windows machine were measured. The emulator runs on the Mac's chip and says nothing about a low-end phone.
- Total per processed frame is the sum of the stages; at 10 fps the engine has 100 ms per frame, so on these numbers it does not keep up with every frame: the load shedder (CNN every Nth frame, oldest frames dropped, the PAD voters never skipped) is what keeps the producer unblocked. The measured effect of that mode on accuracy is not yet available (needs recordings).
- In the engine the passive voters run once per decision, but during a challenge the re-evaluation runs the PAD voters on every processed frame, so the moire FFT cost matters most there.
- The largest cost is the moire FFT; a cheaper variant is the first thing to try for a low-resource mode.
EOF
} > "$ROOT/docs/PERFORMANCE.md"
