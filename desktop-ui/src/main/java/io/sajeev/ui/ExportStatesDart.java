// #53 (WS3) | Writes the 14 UX states and the 13 error screens, with their texts in en/fr/ar, as a Dart file for the
// Flutter widget, so the desktop and Android screens share one definition. Run: ExportStatesDart <out.dart>.
package io.sajeev.ui;

import io.sajeev.api.ErrorState;
import io.sajeev.guidance.GuidanceKeys;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Paths;
import java.util.List;

public final class ExportStatesDart {

    private ExportStatesDart() {
    }

    private static String q(String s) {
        return "'" + s.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$") + "'";
    }

    private static String text(GuidanceKeys g, String key, String lang) {
        return key == null || key.isEmpty() ? "" : g.text(key, lang);
    }

    private static String texts(GuidanceKeys g, String key) {
        StringBuilder b = new StringBuilder("{");
        for (String l : GuidanceKeys.LANGS) {
            b.append(q(l)).append(": ").append(q(text(g, key, l))).append(", ");
        }
        return b.append("}").toString();
    }

    private static String list(GuidanceKeys g, List<String> keys) {
        StringBuilder b = new StringBuilder("[");
        for (String k : keys) {
            b.append(texts(g, k)).append(", ");
        }
        return b.append("]").toString();
    }

    private static String state(GuidanceKeys g, String name, UiState u) {
        return "  LivenessUiState(id: " + q(name) + ", title: " + texts(g, u.titleKey()) + ", badge: " + texts(g, u.badgeKey())
                + ", badgeStyle: " + q(u.badgeStyle().name()) + ", showGuide: " + u.showGuide() + ", icon: " + q(u.icon())
                + ", progressDone: " + u.progressDone() + ", progressTotal: " + u.progressTotal() + ", message: " + texts(g, u.messageKey())
                + ", hints: " + list(g, u.hintKeys()) + ", buttons: " + list(g, u.buttonKeys()) + ", footer: " + texts(g, u.footerKey()) + "),\n";
    }

    public static void main(String[] args) throws IOException {
        GuidanceKeys g = new GuidanceKeys();
        StringBuilder out = new StringBuilder("// GENERATED by sajeev desktop-ui ExportStatesDart (ticket #53). Do not edit by hand.\n"
                + "// Same states and wording as the desktop screens UX1-UX14. French and Arabic are unreviewed translations.\n"
                + "import 'liveness_ui_state.dart';\n\nconst List<LivenessUiState> livenessUxStates = [\n");
        List<UiState> all = UiStates.allUx();
        for (int i = 0; i < all.size(); i++) {
            out.append(state(g, "UX" + (i + 1), all.get(i)));
        }
        out.append("];\n\nconst Map<String, LivenessUiState> livenessErrorStates = {\n");
        for (ErrorState e : ErrorState.values()) {
            out.append("  ").append(q(e.name())).append(": ").append(state(g, e.name(), UiStates.forError(e)).trim().replaceAll(",$", ",")).append("\n");
        }
        out.append("};\n");
        Files.write(Paths.get(args[0]), out.toString().getBytes(StandardCharsets.UTF_8));
        if (args.length > 1) { // every message key in the three languages, for screens built from live progress
            StringBuilder t = new StringBuilder("// GENERATED by ExportStatesDart (ticket #54). Do not edit by hand.\n"
                    + "const Map<String, Map<String, String>> livenessTexts = {\n");
            for (String k : new java.util.TreeSet<>(g.keys("en"))) {
                t.append("  ").append(q(k)).append(": ").append(texts(g, k)).append(",\n");
            }
            t.append("};\n");
            Files.write(Paths.get(args[1]), t.toString().getBytes(StandardCharsets.UTF_8));
        }
    }
}
